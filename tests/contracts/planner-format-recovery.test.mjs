import test from 'node:test';
import assert from 'node:assert/strict';
import {OpenAiCompatibleDatasetMatcher} from '../../dist/src/planning/planner.js';

const input={profile:'STANDARD',agentStaticInfo:{target_type:'FULL_AGENT',plugins:[],tools:[],tool_delta:{},limitations:[]},availableDatasets:[{datasetId:'dataset.demo/v1',name:'Demo',description:'Synthetic file delivery',labelIds:['label.artifact-delivery/v1'],availableCaseCount:1}]};
const plan=reason=>({selected_datasets:[{dataset_id:'dataset.demo/v1',case_count:1,reason}]});
const reply=body=>new Response(JSON.stringify({choices:[{message:{content:JSON.stringify(body)}}]}));

test('automatic planning retries an overlong reason and accepts only the corrected model plan',async()=>{
 const requests=[];
 const matcher=new OpenAiCompatibleDatasetMatcher({endpoint:'https://planner.invalid/chat',apiKey:'fixture-key',model:'fixture-model',fetchImpl:async(_,request)=>{
  requests.push(JSON.parse(request.body));
  return reply(plan(requests.length===1?'长'.repeat(501):'Read the public input and deliver the requested file.'));
 }});
 const selected=await matcher.select(input);
 assert.equal(requests.length,2);
 assert.equal(selected.selectedDatasets[0].reason,'Read the public input and deliver the requested file.');
 assert.equal(selected.totalCaseCount,1);
 assert.deepEqual(selected.evaluationLabelIds,['label.artifact-delivery/v1']);
 assert.deepEqual(requests[0].messages[0],requests[1].messages[0]);
 assert.match(JSON.stringify(requests[1].messages.slice(1)),/selected_datasets\[0\]\.reason/);
 assert.match(JSON.stringify(requests[1].messages.slice(1)),/500/);
});

test('a reason at the existing 500-character boundary succeeds in one request unchanged',async()=>{
 let calls=0;
 const matcher=new OpenAiCompatibleDatasetMatcher({endpoint:'https://planner.invalid/chat',apiKey:'fixture-key',model:'fixture-model',fetchImpl:async()=>{calls++;return reply(plan('长'.repeat(500)));}});
 const selected=await matcher.select(input);
 assert.equal(calls,1);assert.equal(selected.selectedDatasets[0].reason.length,500);
});

test('repeated invalid plans stop after three requests without truncating the reason or leaking the response',async()=>{
 let calls=0;const retries=[];
 const reason='Do not log this rejected response: '+'长'.repeat(501);
 const matcher=new OpenAiCompatibleDatasetMatcher({endpoint:'https://planner.invalid/chat',apiKey:'fixture-key',model:'fixture-model',onValidationRetry:event=>retries.push(event),fetchImpl:async(_,request)=>{
  calls++;assert.ok(!request.body.includes(reason));assert.ok(!request.body.includes('fixture-key'));return reply(plan(reason));
 }});
 await assert.rejects(matcher.select(input),/reason must be 1 to 500 characters/);
 assert.equal(calls,3);assert.deepEqual(retries.map(e=>[e.failedAttempt,e.nextAttempt,e.maxAttempts]),[[1,2,3],[2,3,3]]);
 assert.ok(!JSON.stringify(retries).includes(reason));assert.ok(!JSON.stringify(retries).includes('fixture-key'));
});

test('correction keeps dataset eligibility and case budgets strict',async()=>{
 for(const body of [{selected_datasets:[{dataset_id:'dataset.unknown/v1',case_count:1,reason:'fixture'}]},plan('fixture')]){
  if(body.selected_datasets[0].dataset_id==='dataset.demo/v1')body.selected_datasets[0].case_count=2;
  let calls=0;
  const matcher=new OpenAiCompatibleDatasetMatcher({endpoint:'https://planner.invalid/chat',apiKey:'fixture-key',model:'fixture-model',fetchImpl:async()=>{calls++;return reply(body);}});
  await assert.rejects(matcher.select(input),/not an available Dataset|violates the Dataset/);
  assert.equal(calls,3);
 }
});

test('a malformed reply is regenerated by the model before its plan can be admitted',async()=>{
 let calls=0;const retries=[];
 const matcher=new OpenAiCompatibleDatasetMatcher({endpoint:'https://planner.invalid/chat',apiKey:'fixture-key',model:'fixture-model',onValidationRetry:event=>retries.push(event),fetchImpl:async()=>{
  calls++;
  if(calls===1)return new Response(JSON.stringify({choices:[{message:{content:'```json\ninvalid reply\n```'}}]}));
  return reply(plan('Model regenerated a complete valid plan.'));
 }});
 const selected=await matcher.select(input);
 assert.equal(calls,2);assert.equal(selected.selectedDatasets[0].reason,'Model regenerated a complete valid plan.');
 assert.equal(retries[0].reason,'Unified Planner returned invalid JSON');
});

test('HTTP failures are not treated as model-format errors',async()=>{
 let calls=0;const retries=[];
 const matcher=new OpenAiCompatibleDatasetMatcher({endpoint:'https://planner.invalid/chat',apiKey:'fixture-key',model:'fixture-model',onValidationRetry:event=>retries.push(event),fetchImpl:async()=>{calls++;return new Response('',{status:503});}});
 await assert.rejects(matcher.select(input),/HTTP 503/);assert.equal(calls,1);assert.deepEqual(retries,[]);
});

test('cancellation during a rejected response prevents another model request',async()=>{
 const controller=new AbortController(),cancelled=Error('Fixture cancelled');let calls=0;const retries=[];
 const matcher=new OpenAiCompatibleDatasetMatcher({endpoint:'https://planner.invalid/chat',apiKey:'fixture-key',model:'fixture-model',onValidationRetry:event=>retries.push(event),fetchImpl:async()=>{calls++;controller.abort(cancelled);return reply(plan('长'.repeat(501)));}});
 await assert.rejects(matcher.select({...input,signal:controller.signal}),error=>error===cancelled);
 assert.equal(calls,1);assert.deepEqual(retries,[]);
});
